/// Port of the legacy `DirToByte` best-match search.
pub fn dir_to_byte(dir: [f32; 3]) -> u8 {
    if dir == [0.0; 3] {
        return DIRECTION_COUNT as u8;
    }
    let normalized = dir[0] * dir[0] + dir[1] * dir[1] + dir[2] * dir[2] == 1.0;
    let mut best = 0;
    let mut best_dot = 0.0;
    for (index, candidate) in DIRECTIONS.iter().enumerate() {
        let dot = dir[0] * candidate[0] + dir[1] * candidate[1] + dir[2] * candidate[2];
        if dot == 1.0 && normalized {
            return index as u8;
        }
        if dot > best_dot {
            best_dot = dot;
            best = index;
        }
    }
    best as u8
}
